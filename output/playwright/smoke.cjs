const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({headless:true, executablePath:process.env.CHROMIUM_EXECUTABLE});
 try {
 const page = await browser.newPage();
 const errors=[]; page.on('pageerror', e=>errors.push(e.message));
 let requests=0; const scripts=[];
 page.on('request', r=>{if(r.url().endsWith('search-index.json')) requests++; if(r.resourceType()==='script') scripts.push(r.url());});
 await page.goto('http://127.0.0.1:4321/');
 await page.waitForLoadState('networkidle');
 assert.equal(requests,0);
 assert.equal(scripts.some(s=>/\/index\.[^/]+\.js/.test(s)),false);
 const canonical=await page.locator('link[rel="canonical"]').getAttribute('href'); assert.match(canonical,/https:\/\/notes.adihuang.com\/notes\//);
 const input=page.locator('[data-search-input]');
 let release; const gate=new Promise(r=>release=r);
 await page.route('**/search-index.json',async route=>{await gate; await route.continue();});
 await input.focus(); await input.fill('not-a-real-result-zzzz');
 await page.waitForFunction(()=>document.querySelector('[data-search-status]').textContent==='Loading search…');
 await input.fill('git'); release();
 await page.waitForFunction(()=>/articles?$/.test(document.querySelector('[data-search-status]').textContent));
 assert.equal(requests,1);
 assert.ok(await page.locator('[data-article-link]:visible').count()>0);
 await input.fill('zzzznonexistent');
 await page.waitForFunction(()=>document.querySelector('[data-search-status]').textContent.startsWith('No notes found'));
 assert.ok(await page.locator('[data-search-status]').isVisible());
 await input.fill(''); await input.press('Tab');
 assert.equal(await page.evaluate(()=>document.activeElement.className),'search-tag');
 await page.keyboard.press('Enter'); assert.notEqual(await input.inputValue(),'');
 await input.press('Escape'); assert.equal(await page.locator('[data-search-popover]').isVisible(),false);
 await page.locator('#articles-tab').focus(); await page.keyboard.press('ArrowRight');
 assert.equal(await page.locator('#outline-tab').getAttribute('aria-selected'),'true');
 assert.equal(await page.locator('#articles-panel').isVisible(),false);
 await page.keyboard.press('Home'); assert.equal(await page.locator('#articles-tab').getAttribute('aria-selected'),'true');
 await page.setViewportSize({width:390,height:844});
 await page.locator('[data-menu-button]').click(); await page.locator('#outline-tab').click(); await input.fill('git');
 assert.equal(await page.locator('#articles-tab').getAttribute('aria-selected'),'true');
 assert.match(await page.locator('[data-shell]').getAttribute('class'),/is-sidebar-open/);
 await page.screenshot({path:'output/playwright/mobile-search.png'});
 await page.locator('[data-article-link]:visible').first().click();
 await page.waitForLoadState('networkidle'); assert.match(page.url(),/\/notes\//);
 for (const mode of ['404','json','shape','offline']) {
  await page.unroute('**/search-index.json');
  await page.route('**/search-index.json',r=>mode==='offline'?r.abort():r.fulfill({status:mode==='404'?404:200,contentType:'application/json',body:mode==='json'?'invalid':'{}'}));
  await page.goto('http://127.0.0.1:4321/'); await input.focus();
  await page.waitForFunction(()=>document.querySelector('[data-search-status]').textContent==='Search temporarily unavailable');
  assert.ok(await page.locator('[data-search-status]').isVisible());
  assert.equal(await page.locator('[data-article-link][hidden]').count(),0);
  await page.locator('[data-search-retry]').focus();
  await page.keyboard.press('Enter');
  await page.waitForFunction(()=>document.querySelector('[data-search-status]').textContent==='Search temporarily unavailable');
  assert.ok(await page.locator('[data-search-status]').isVisible());
  assert.ok(await page.locator('[data-search-retry]').isVisible());
  assert.equal(await input.evaluate(el=>el===document.activeElement),true);
  await page.unroute('**/search-index.json');
  let resumeRetry;
  const retryGate = new Promise(resolve=>resumeRetry=resolve);
  await page.route('**/search-index.json',async route=>{await retryGate; await route.continue();});
  await page.locator('[data-search-retry]').click();
  await page.waitForFunction(()=>document.querySelector('[data-search-status]').textContent==='Loading search…');
  assert.ok(await page.locator('[data-search-status]').isVisible());
  assert.equal(await input.evaluate(el=>el===document.activeElement),true);
  resumeRetry();
  await page.waitForFunction(()=>document.querySelector('[data-search-status]').textContent==='Select a tag');
  assert.ok(await page.locator('[data-search-status]').isVisible());
  assert.ok(await page.locator('[data-search-results]').isVisible());
  assert.equal(await input.evaluate(el=>el===document.activeElement),true);
 }
 const response=await page.goto('http://127.0.0.1:4321/does-not-exist');
 assert.equal(response.status(),404); assert.equal(await page.locator('h1').textContent(),'Note not found');
 assert.deepEqual(errors,[]);
 console.log('Passed: lazy request/import, pending input, single initialization, empty state, keyboard tags/tabs, mobile search/navigation, 404/JSON/schema/offline recovery, canonical and 404.');
 } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exit(1)});
